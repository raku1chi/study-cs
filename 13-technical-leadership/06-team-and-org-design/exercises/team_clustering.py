def refine_teams(
    teams: list[list[str]],
    coupling: dict[Pair, float],
    load: dict[str, float],
    max_load: float,
) -> list[list[str]]:
    """コンポーネントを 1 つずつ別のチームに動かして、チーム間の結合を減らす（局所探索）。

    コンポーネント c をチーム S からチーム T に動かしたときの利得:
        利得 = (c と T の要素の結合の合計) − (c と S の他の要素の結合の合計)
    利得が正なら、チームをまたぐ結合の合計がちょうどその分だけ減る。

    1. 空のチームを除き、各チームを名前の昇順、チームを先頭の名前の昇順に並べる
    2. 移動先の負荷の合計が max_load を超えない移動のうち、利得が正で最大の移動を 1 つ行う。
       同点なら、動かすコンポーネントの名前が小さい方、それも同じなら移動先のチームの
       先頭の名前が小さい方を選ぶ
    3. 移動元が空になったらそのチームは消える（チームの数が減ることがある）。1 に戻る
    4. 利得が正の移動がなくなったら、1 と同じ順に並べたチームを返す

    - 同じコンポーネントが複数のチームにある、負荷が max_load を超えるチームがある → ValueError

    >>> coupling = {("a", "b"): 1, ("a", "c"): 5}
    >>> refine_teams([["a", "b"], ["c"]], coupling, {c: 1 for c in "abc"}, max_load=2)
    [['a', 'c'], ['b']]

    ヒント: 利得が正の移動だけを行うので、チームをまたぐ結合は毎回必ず減り、手続きは必ず終わる。
    ただし、見つかるのは「1 つ動かすだけでは改善できない」局所最適であり、最適とは限らない。
    """
    raise NotImplementedError("演習4: refine_teams を実装してください")
