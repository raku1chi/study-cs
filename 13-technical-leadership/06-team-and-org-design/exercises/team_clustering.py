# ---------------------------------------------------------------------------
# 演習3（★★★）: 貪欲な凝集型クラスタリング
# ---------------------------------------------------------------------------

def greedy_teams(
    components: list[str],
    coupling: dict[Pair, float],
    load: dict[str, float],
    max_load: float,
    target_teams: int | None = None,
) -> list[list[str]]:
    """結合の強いもの同士を貪欲に併合して、チームの分け方を提案する。

    クラスタ = コンポーネントの集まり。クラスタの負荷 = 含まれるコンポーネントの load の合計。
    2 つのクラスタの結合 = 片方の要素と他方の要素のすべての組の重みの合計。

    1. 各コンポーネントを 1 つのクラスタとして始める
    2. 第 1 段階: 負荷の合計が max_load 以下になる組のうち、結合が正で最大の組を併合する。
       これを、併合できる組がなくなるか、クラスタの数が target_teams 以下になるまで繰り返す
    3. 第 2 段階（target_teams が指定されていて、まだクラスタの数がそれより多いときだけ）:
       負荷の合計が max_load 以下になる組のうち、負荷の合計が最小の組を併合する。
       これを、併合できる組がなくなるか、クラスタの数が target_teams 以下になるまで繰り返す
       （目標のチーム数に届かないこともある）
    4. 各チームを名前の昇順に並べ、チームを先頭の名前の昇順に並べて返す

    同点の扱い（結果を決定的にするため）: 各クラスタを「そのクラスタで名前が最小の要素」で代表させ、
    2 つの代表の組 (小さい方, 大きい方) が辞書順で最も先の組を選ぶ。

    - components が空または重複あり、load にないコンポーネントがある、
      1 つのコンポーネントの負荷が max_load を超える、target_teams が 1 未満 → ValueError

    >>> coupling = {("a", "b"): 5, ("c", "d"): 4, ("b", "c"): 1}
    >>> greedy_teams(["a", "b", "c", "d"], coupling, {c: 1 for c in "abcd"}, max_load=2)
    [['a', 'b'], ['c', 'd']]

    ヒント: 毎回すべてのクラスタの組を調べる素朴な実装で十分（コンポーネントは数十個まで）。
    """
